"""Build the serializable-command catalogue straight from the binary (no model, no worker text).

Every network command class derives from PersistentBase: vtable slot 2 is the shared class-header writer 013aede0 and
slot 6 is a `mov eax, <classID>; ret` getter (slot 8 the same shape for the version). Scanning every RTTI vtable for
that shape gives an exact classID -> class table, including classes nobody has mapped yet. Labels (when accepted or
ingested) are attached for the Read/Write/handler slots.

  python -I commands.py --run <run dir>          writes table `command` in map.sqlite and notes/Native Map/Commands.md
Query with: python -I nmq.py command <classID | name regex>
"""
import argparse, json, re, sqlite3, struct, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from vslots import PE

HEADER_WRITER = 0x013aede0
VAULT = HERE.parent.parent / "notes" / "Native Map" / "Commands.md"


class Image:
    def __init__(self, path=PE):
        self.d = Path(path).read_bytes()
        pe = struct.unpack_from("<I", self.d, 0x3C)[0]
        n, opt = struct.unpack_from("<H", self.d, pe + 6)[0], struct.unpack_from("<H", self.d, pe + 20)[0]
        self.base = struct.unpack_from("<I", self.d, pe + 24 + 28)[0]
        self.secs = [struct.unpack_from("<IIII", self.d, pe + 24 + opt + 40 * i + 8) for i in range(n)]

    def off(self, va):
        rva = va - self.base
        for vs, v, rs, raw in self.secs:
            if v <= rva < v + min(max(vs, rs), rs or vs):
                return raw + rva - v
        return None

    def u32(self, va):
        o = self.off(va)
        return struct.unpack_from("<I", self.d, o)[0] if o is not None else None

    def imm_getter(self, va):
        """value of a `mov eax, imm32; ret` function, else None"""
        o = self.off(va) if va else None
        if o is None:
            return None
        b = self.d[o:o + 6]
        return struct.unpack_from("<I", b, 1)[0] if len(b) == 6 and b[0] == 0xB8 and b[5] == 0xC3 else None


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--run", required=True)
    a = ap.parse_args()
    db = sqlite3.connect(Path(a.run) / "map.sqlite", timeout=60)
    img = Image()
    vts = {}
    for (vs,) in db.execute("SELECT vslots FROM fn WHERE vslots IS NOT NULL"):
        for e in json.loads(vs):
            m = re.match(r"([0-9a-f]{8}) (.+?)::vftable", e)
            if m:
                vts.setdefault(int(m.group(1), 16), m.group(2))
    lab = {}
    for addr, rec, shard in db.execute("SELECT l.addr, l.record, f.shard FROM label l JOIN fn f ON f.addr=l.addr"):
        r = json.loads(rec)
        lab[addr] = (r.get("refined_name") or r.get("name"), r.get("confidence"), shard)
    shard_of = dict(db.execute("SELECT addr, shard FROM fn"))
    rows = []
    for vt, name in sorted(vts.items()):
        if img.u32(vt + 8) != HEADER_WRITER:
            continue
        cid = img.imm_getter(img.u32(vt + 24))
        if cid is None:
            continue  # abstract base without its own classID getter
        slot = {k: img.u32(vt + 4 * k) for k in (9, 10, 15, 21)}
        ver = img.imm_getter(img.u32(vt + 32))
        family = name.split("_")[0] if "_" in name else name
        # slots 15/21 are the client handler / routing triple only for NetworkCommand-style classes; for state
        # machine states, expressions etc. those slots are ordinary game virtuals (S0761: DoublePassState slot 21 = CardPlayed)
        is_cmd = family.endswith("Command") or family in ("CommandObject", "CWCommandObject")
        # CommandObject classes are multiply inherited: the scanned (serialisable) table is the secondary one at obj+8,
        # where slot 15 is not a handler (S0756: it is the deleting dtor); their logic lives in DoCommand on the primary
        h = f"{slot[15]:08x}" if slot[15] and family.endswith("Command") else ""
        if not is_cmd:
            slot[21] = None
        rows.append((cid, name, family, ver, f"{vt:08x}", f"{slot[9]:08x}", f"{slot[10]:08x}", h, (f"{slot[21]:08x}" if slot[21] else ""),
                     shard_of.get(f"{slot[9]:08x}"), (lab.get(f"{slot[9]:08x}") or (None, None, None))[1]))
    db.execute("DROP TABLE IF EXISTS command")
    db.execute("CREATE TABLE command(class_id INTEGER, class TEXT, family TEXT, version INTEGER, vtable TEXT, read TEXT, "
               "write TEXT, handler TEXT, routing TEXT, shard TEXT, read_label_conf TEXT)")
    db.executemany("INSERT INTO command VALUES(?,?,?,?,?,?,?,?,?,?,?)", rows)
    db.commit()
    dup = {}
    for r in rows:
        dup.setdefault(r[0], []).append(r[1])
    fams = {}
    for r in rows:
        fams.setdefault(r[2], []).append(r)
    out = ["# Command catalogue", "",
           "Generated by `scripts/native_map/commands.py` straight from FreeRealms.exe: every class whose vtable slot 2 is the",
           "PersistentBase header writer `013aede0` and whose slot 6 is `mov eax, classID; ret`. Wire format (lead-verified):",
           "frame `[htonl(len+12)][3 routing ints from slot 21][body]` (`012d0810` → `012f0a00`); body = (classID, version)",
           "header once per inheritance level, then each level's fields (Write = slot 10, Read = slot 9). Slot 15 is the client",
           "handler. Field layouts and event codes are in the shard findings linked below. Slot numbers assume the standard",
           "command template; a few classes (e.g. FriendStatus, IgnoreStatus) have shifted vtables, so check their shard notes.", "",
           f"**{len(rows)} command classes in {len(fams)} families.**", ""]
    for fam in sorted(fams):
        out += [f"## {fam} ({len(fams[fam])})", "", "| classID | class | ver | Read | Write | handler | routing | shard |",
                "|---|---|---|---|---|---|---|---|"]
        for r in sorted(fams[fam]):
            sh = f"[[{r[9]}]]" if r[9] else ""
            out.append(f"| {r[0]} (0x{r[0]:x}) | {r[1]} | {r[3] if r[3] is not None else ''} | `{r[5]}` | `{r[6]}` | `{r[7]}` | `{r[8]}` | {r[9] or ''} |")
        out.append("")
    clashes = {k: v for k, v in dup.items() if len(v) > 1}
    if clashes:
        out += ["## classIDs shared by several classes", ""] + [f"- {k} (0x{k:x}): {', '.join(v)}" for k, v in sorted(clashes.items())]
    VAULT.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"commands={len(rows)} families={len(fams)} shared_ids={len(clashes)} -> {VAULT}")


if __name__ == "__main__":
    main()
